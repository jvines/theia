// SAOImage DS9's built-in colour maps. The definitions are those of JS9
// (https://github.com/ericmandel/js9, MIT licence, Smithsonian Institution),
// which match DS9's own; see THIRD-PARTY-NOTICES.md. Piecewise-linear maps are
// DS9's "SAO" format, one list of (position, intensity) vertices per channel;
// table maps are DS9 LUTs of evenly spaced colours.
enum DS9ColorMaps {
    struct Vertices {
        let red: [SIMD2<Float>]
        let green: [SIMD2<Float>]
        let blue: [SIMD2<Float>]
    }

    /// DS9's evaluation of an SAO map: interpolate between the vertices either
    /// side of `x`, so a repeated position makes a step.
    static func sample(_ vertices: Vertices, at x: Float) -> SIMD3<Float> {
        SIMD3(channel(vertices.red, x), channel(vertices.green, x), channel(vertices.blue, x))
    }

    /// DS9's evaluation of a LUT: evenly spaced, equal-width bands.
    static func sample(_ table: [SIMD3<Float>], at x: Float) -> SIMD3<Float> {
        table[min(table.count - 1, max(0, Int(x * Float(table.count))))]
    }

    private static func channel(_ vertices: [SIMD2<Float>], _ x: Float) -> Float {
        guard let next = vertices.firstIndex(where: { $0.x > x }) else { return vertices.last!.y }
        guard next > 0 else { return vertices[0].y }
        let a = vertices[next - 1], b = vertices[next]
        let slope = (b.y - a.y) / (b.x - a.x)
        return slope == 0 ? b.y : a.y + slope * (x - a.x)
    }

    private static func v(_ points: [(Float, Float)]) -> [SIMD2<Float>] {
        points.map { SIMD2($0.0, $0.1) }
    }

