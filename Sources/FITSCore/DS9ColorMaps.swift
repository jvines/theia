    /// 200 colours walked through HSV: hue from 270° round to 270°, saturation
    /// sin(π·f), value (1 − f)^⅓, with f running from 1 to 0.
    static let hsv: [SIMD3<Float>] = (0..<200).map { index in
        let fraction = 1 - Double(index) / 199
        var hue = fraction * 360 + 270
        while hue >= 360 { hue -= 360 }
        hue /= 60
        let saturation = abs(sin(fraction * 3.1416))
        let value = pow(1 - fraction, 1.0 / 3)
        let sector = Int(hue.rounded(.down))
        let f = hue - Double(sector)
        let p = value * (1 - saturation)
        let q = value * (1 - saturation * f)
        let t = value * (1 - saturation * (1 - f))
        let rgb: (Double, Double, Double)
        switch sector {
        case 0: rgb = (value, t, p)
        case 1: rgb = (q, value, p)
        case 2: rgb = (p, value, t)
        case 3: rgb = (p, q, value)
        case 4: rgb = (t, p, value)
        default: rgb = (value, p, q)
        }
        return SIMD3(Float(rgb.0), Float(rgb.1), Float(rgb.2))
    }
