// (Copyright (c) 2012- Matplotlib Development Team; see THIRD-PARTY-NOTICES.md).
// Segment maps are piecewise linear between (position, intensity) vertices;
// function maps evaluate matplotlib's formulas clipped to [0, 1], as matplotlib
// does; listed maps interpolate between their 256 entries.
enum MatplotlibColorMaps {
    struct Segments {
        let red: [SIMD2<Float>]
        let green: [SIMD2<Float>]
        let blue: [SIMD2<Float>]
    }

    static func sample(_ segments: Segments, at x: Float) -> SIMD3<Float> {
        SIMD3(channel(segments.red, x), channel(segments.green, x), channel(segments.blue, x))
    }

    static func sample(_ table: [SIMD3<Float>], at x: Float) -> SIMD3<Float> {
        let position = x * Float(table.count - 1)
        let index = min(table.count - 2, max(0, Int(position)))
        let fraction = position - Float(index)
        return table[index] + (table[index + 1] - table[index]) * fraction
    }

    private static func channel(_ vertices: [SIMD2<Float>], _ x: Float) -> Float {
        guard let next = vertices.firstIndex(where: { $0.x > x }) else { return vertices.last!.y }
        guard next > 0 else { return vertices[0].y }
        let a = vertices[next - 1], b = vertices[next]
        return a.y + (b.y - a.y) * (x - a.x) / (b.x - a.x)
    }

    private static func v(_ points: [(Float, Float)]) -> [SIMD2<Float>] {
        points.map { SIMD2($0.0, $0.1) }
    }

    private static func clipped(_ r: Double, _ g: Double, _ b: Double) -> SIMD3<Float> {
        SIMD3(Float(min(1, max(0, r))), Float(min(1, max(0, g))), Float(min(1, max(0, b))))
    }

