    static func rainbow(_ x: Double) -> SIMD3<Float> {
        clipped(abs(2 * x - 0.5), sin(x * .pi), cos(x * .pi / 2))
    }

    /// D. A. Green's cubehelix (2011, BASI 39, 289) with matplotlib's defaults:
    /// gamma 1, start 0.5, rotations -1.5, hue 1.
    static func cubehelix(_ x: Double) -> SIMD3<Float> {
        let amplitude = x * (1 - x) / 2
        let angle = 2 * Double.pi * (0.5 / 3 - 1.5 * x)
        func channel(_ p0: Double, _ p1: Double) -> Double {
            x + amplitude * (p0 * cos(angle) + p1 * sin(angle))
        }
        return clipped(channel(-0.14861, 1.78277), channel(-0.29227, -0.90649), channel(1.97294, 0))
    }

